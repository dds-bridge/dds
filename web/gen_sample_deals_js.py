#!/usr/bin/env python3
"""Emit web/dds_web_sample_deals.js from a manifest of hands/*.pbn files.

Usage (from repo root):
  python3 web/gen_sample_deals_js.py
  python3 web/gen_sample_deals_js.py --repo-root . --manifest web/sample_deals_manifest.json \\
      --output web/dds_web_sample_deals.js
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

DEAL_RE = re.compile(r'\[Deal\s+"([^"]+)"\s*\]', re.IGNORECASE)

HEADER = """\
// Copyright 2020-2026 Adam Wildavsky
//
//   Use of this source code is governed by an MIT-style
//   license that can be found in the LICENSE file or at
//   https://opensource.org/licenses/MIT

// Generated by web/gen_sample_deals_js.py — do not edit.
// Source: web/sample_deals_manifest.json + hands/*.pbn
// Regenerate: python3 web/gen_sample_deals_js.py

/* eslint-env es6 */
/* exported SAMPLE_DEALS */

"use strict";

(function (global) {
    global.SAMPLE_DEALS = {
"""

FOOTER = """\
    };
})(typeof globalThis !== "undefined" ? globalThis : window);
"""


def extract_deal_string(pbn_text: str) -> str:
    """Return the Deal payload (e.g. N:...) from a PBN file body."""
    match = DEAL_RE.search(pbn_text)
    if not match:
        raise ValueError("no [Deal \"...\"] tag found")
    return match.group(1)


def load_samples_from_manifest(
    manifest: list[dict], repo_root: Path
) -> list[dict]:
    """Resolve each manifest entry to id, name, and PBN deal string."""
    samples: list[dict] = []
    for entry in manifest:
        rel = entry["file"]
        path = repo_root / rel
        if not path.is_file():
            raise FileNotFoundError(f"missing PBN file: {rel}")
        pbn = extract_deal_string(path.read_text(encoding="utf-8"))
        samples.append(
            {
                "id": entry["id"],
                "name": entry["name"],
                "pbn": pbn,
            }
        )
    return samples


def make_sample_deals_js(samples: list[dict]) -> str:
    """Return dds_web_sample_deals.js contents for the given samples."""
    lines = [HEADER]
    for i, sample in enumerate(samples):
        comma = "," if i + 1 < len(samples) else ""
        deal_id = json.dumps(sample["id"])
        name = json.dumps(sample["name"])
        pbn = json.dumps(sample["pbn"])
        lines.append(f"        {deal_id}: {{\n")
        lines.append(f"            name: {name},\n")
        lines.append(f"            pbn: {pbn}\n")
        lines.append(f"        }}{comma}\n")
    lines.append(FOOTER)
    return "".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate dds_web_sample_deals.js from hands/*.pbn"
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=None,
        help="repository root (default: parent of web/)",
    )
    parser.add_argument(
        "--manifest",
        type=Path,
        default=None,
        help="path to sample_deals_manifest.json",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="output JS path",
    )
    args = parser.parse_args(argv)

    script_web = Path(__file__).resolve().parent
    repo_root = (args.repo_root or script_web.parent).resolve()
    manifest_path = (
        args.manifest or script_web / "sample_deals_manifest.json"
    ).resolve()
    output_path = (args.output or script_web / "dds_web_sample_deals.js").resolve()

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    samples = load_samples_from_manifest(manifest, repo_root)
    output_path.write_text(make_sample_deals_js(samples), encoding="utf-8")
    print(f"wrote {output_path} ({len(samples)} sample deals)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
