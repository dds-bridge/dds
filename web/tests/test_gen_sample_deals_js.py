"""Tests for generating web/dds_web_sample_deals.js from hands/*.pbn."""

from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

WEB_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = WEB_ROOT.parent


def _load_gen():
    path = WEB_ROOT / "gen_sample_deals_js.py"
    spec = importlib.util.spec_from_file_location("gen_sample_deals_js", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Unable to load {path}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


class GenSampleDealsJsTest(unittest.TestCase):
    def test_extract_deal_from_pbn_tag(self) -> None:
        gen = _load_gen()
        text = '{comment}\n[Deal "N:AK.Q.J.T 234.234.234.234 567.567.567.567 89T.89T.89T.89T"]\n'
        self.assertEqual(
            gen.extract_deal_string(text),
            "N:AK.Q.J.T 234.234.234.234 567.567.567.567 89T.89T.89T.89T",
        )

    def test_extract_deal_raises_when_missing(self) -> None:
        gen = _load_gen()
        with self.assertRaises(ValueError):
            gen.extract_deal_string("no deal here\n")

    def test_sample_id_from_file_uses_basename(self) -> None:
        gen = _load_gen()
        self.assertEqual(gen.sample_id_from_file("hands/part_score.pbn"), "part_score")
        self.assertEqual(
            gen.sample_id_from_file("hands/everyone_makes_3N.pbn"),
            "everyone_makes_3N",
        )

    def test_make_sample_deals_js_emits_name_and_pbn(self) -> None:
        gen = _load_gen()
        samples = [
            {
                "id": "part_score",
                "name": "Part-score",
                "pbn": "N:AQ85.AK976.5.J87 JT.QJ5432.Q9.KQ9 972..JT863.A6432 K643.T8.AK742.T5",
            }
        ]
        js = gen.make_sample_deals_js(samples)
        self.assertIn("Generated by web/gen_sample_deals_js.py", js)
        self.assertIn("SAMPLE_DEALS", js)
        self.assertIn('"part_score"', js)
        self.assertIn("Part-score", js)
        self.assertIn("AQ85.AK976.5.J87", js)
        self.assertNotIn("hands:", js)

    def test_load_samples_from_manifest_reads_hands_pbn(self) -> None:
        gen = _load_gen()
        manifest = [
            {
                "name": "Part-score",
                "file": "hands/part_score.pbn",
            }
        ]
        samples = gen.load_samples_from_manifest(manifest, REPO_ROOT)
        self.assertEqual(len(samples), 1)
        self.assertEqual(samples[0]["id"], "part_score")
        self.assertEqual(samples[0]["name"], "Part-score")
        self.assertTrue(samples[0]["pbn"].startswith("N:AQ85.AK976.5.J87"))

    def test_manifest_entries_do_not_require_id(self) -> None:
        gen = _load_gen()
        manifest_path = WEB_ROOT / "sample_deals_manifest.json"
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        for entry in manifest:
            self.assertNotIn("id", entry)
            self.assertIn("file", entry)
            self.assertIn("name", entry)

    def test_checked_in_sample_deals_js_matches_generator(self) -> None:
        # Arrange / Act: regenerate from the committed manifest and PBN files.
        gen = _load_gen()
        manifest_path = WEB_ROOT / "sample_deals_manifest.json"
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        samples = gen.load_samples_from_manifest(manifest, REPO_ROOT)
        expected = gen.make_sample_deals_js(samples)
        actual = (WEB_ROOT / "dds_web_sample_deals.js").read_text(encoding="utf-8")

        # Assert: run gen_sample_deals_js.py after editing hands/ or the manifest.
        self.assertEqual(
            actual,
            expected,
            msg="dds_web_sample_deals.js is stale; run: "
            "python3 web/gen_sample_deals_js.py",
        )

    def test_cli_writes_output(self) -> None:
        with tempfile.TemporaryDirectory() as tmpdir:
            out_path = Path(tmpdir) / "out.js"
            proc = subprocess.run(
                [
                    sys.executable,
                    str(WEB_ROOT / "gen_sample_deals_js.py"),
                    "--repo-root",
                    str(REPO_ROOT),
                    "--manifest",
                    str(WEB_ROOT / "sample_deals_manifest.json"),
                    "--output",
                    str(out_path),
                ],
                capture_output=True,
                text=True,
                check=False,
            )
            self.assertEqual(proc.returncode, 0, msg=proc.stdout + proc.stderr)
            text = out_path.read_text(encoding="utf-8")
            self.assertIn("Everyone makes 3N", text)
            self.assertIn("Part-score", text)
            self.assertIn("NS make 7", text)


if __name__ == "__main__":
    unittest.main()
